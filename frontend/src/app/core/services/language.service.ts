@Injectable({
  providedIn: 'root'
})
export class LanguageService {
  private readonly STORAGE_KEY = 'lms_selected_language';
  readonly languages = SUPPORTED_LANGUAGES;

  // Signal reactivo para el idioma actual
  currentLang = signal<SupportedLanguage>(this.getInitialLanguage());

  // Signal computado para la opción activa
  currentOption = computed(() => {
    const code = this.currentLang();
    return this.languages.find(l => l.code === code) ?? this.languages[0];
  });

  constructor() {
    if (typeof document !== 'undefined') {
      document.documentElement.lang = this.currentLang();
    }
  }

  private getInitialLanguage(): SupportedLanguage {
    if (typeof localStorage !== 'undefined') {
      const saved = localStorage.getItem(this.STORAGE_KEY) as SupportedLanguage;
      if (saved && (saved === 'es' || saved === 'en' || saved === 'zh' || saved === 'ja' || saved === 'pt')) {
        return saved;
      }
    }
    if (typeof navigator !== 'undefined' && navigator.language) {
      const prefix = navigator.language.slice(0, 2).toLowerCase() as SupportedLanguage;
      if (prefix === 'en' || prefix === 'zh' || prefix === 'ja' || prefix === 'pt') {
        return prefix;
      }
    }
    return 'es';
  }

  public setLanguage(lang: SupportedLanguage): void {
    this.currentLang.set(lang);
    if (typeof localStorage !== 'undefined') {
      localStorage.setItem(this.STORAGE_KEY, lang);
    }
    if (typeof document !== 'undefined') {
      document.documentElement.lang = lang;
    }
  }

  public translatePhrase(text: string, lang: SupportedLanguage): string {
    if (lang === 'es' || !text) return text;

    // 1. Coincidencia exacta en PHRASES
    if (PHRASES[text]?.[lang]) {
      return PHRASES[text][lang];
    }

    // 2. Coincidencia con emoji de prefijo (ej. "🎒 Mis Clases Activas")
    const emojiMatch = text.match(/^([\p{Emoji}\p{Extended_Pictographic}\s]+)(.+)$/u);
    if (emojiMatch) {
      const prefix = emojiMatch[1];
      const rest = emojiMatch[2].trim();
      if (PHRASES[rest]?.[lang]) {
        return prefix + PHRASES[rest][lang];
      }
    }

    // 3. Diccionario de palabras contextuales
    if (WORDS[text]?.[lang]) {
      return WORDS[text][lang];
    }

    // 4. Frases compuestas con números (ej. "🎒 Mis Clases Activas (2)")
    const countMatch = text.match(/^(.+?)\s*\((\d+)\)$/);
    if (countMatch) {
      const base = countMatch[1].trim();
      const num = countMatch[2];
      const transBase = this.translatePhrase(base, lang);
      if (transBase && transBase !== base) {
        return `${transBase} (${num})`;
      }
    }

    // 5. Reemplazos de palabras y frases conocidas en cadenas compuestas
    let replaced = text;
    for (const [key, map] of Object.entries(WORDS)) {
      if (replaced.includes(key)) {
        replaced = replaced.split(key).join(map[lang]);
      }
    }
    for (const [key, map] of Object.entries(PHRASES)) {
      if (replaced.includes(key)) {
        replaced = replaced.split(key).join(map[lang]);
      }
    }

    return replaced;
  }

  public translate(key: string, fallback?: string): string {
    const lang = this.currentLang();

    // 1. Clave jerárquica en TRANSLATIONS para el idioma solicitado
    if (TRANSLATIONS[lang]?.[key]) {
      return TRANSLATIONS[lang][key];
    }

    // 2. Si estamos en español, retornar el valor en español de la clave o fallback
    if (lang === 'es') {
      return TRANSLATIONS['es']?.[key] || fallback || key;
    }

    // 3. Obtener el texto en español asociado a la clave
    const spanish = TRANSLATIONS['es']?.[key] || key;

    // 4. Buscar en el diccionario de frases literales por clave directa o texto en español
    if (PHRASES[key]?.[lang]) {
      return PHRASES[key][lang];
    }
    if (PHRASES[spanish]?.[lang]) {
      return PHRASES[spanish][lang];
    }

    // 5. Traducir frase compuesta dinámicamente
    const translated = this.translatePhrase(spanish, lang);
    if (translated && translated !== spanish) {
      return translated;
    }

    return fallback || spanish || key;
  }

  public t(key: string, fallback?: string): string {
    return this.translate(key, fallback);
  }
}
